import { OUT, getJson, launchBrowser } from '../lib.mjs';
await getJson('http://127.0.0.1:4190/__cloud/reset');
const dump = (c) => getJson(`http://127.0.0.1:4190/__cloud/dump?uid=uid-me@example.com&collection=${c}`);
const browser = await launchBrowser();
const ctx = await browser.newContext({ viewport: { width: 360, height: 800 }, deviceScaleFactor: 2, locale: 'ka-GE', serviceWorkers: 'block' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const ok = (l, c) => console.log((c ? 'OK   ' : 'FAIL ') + l);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.goto('http://127.0.0.1:4190/manifest.webmanifest');
await page.evaluate(() => new Promise((resolve, reject) => {
  const req = indexedDB.open('todo-db', 50);
  req.onupgradeneeded = () => { const d = req.result;
    const notes = d.createObjectStore('notes', { keyPath: 'id' }); for (const k of ['updatedAt', 'deletedAt', 'color', 'groupId']) notes.createIndex(k, k);
    const groups = d.createObjectStore('groups', { keyPath: 'id' }); for (const k of ['updatedAt', 'deletedAt']) groups.createIndex(k, k);
    d.createObjectStore('sync', { keyPath: 'key' }); d.createObjectStore('tombstones', { keyPath: 'key' }); d.createObjectStore('pendingSnapshots', { keyPath: 'id' }); };
  req.onsuccess = () => { const d = req.result; const tx = d.transaction('notes', 'readwrite'); const now = Date.now();
    const mk = (id, title, body) => ({ id, kind: 'text', title, body, items: [], color: 'yellow', groupId: null, date: null, pinned: false, archived: false, createdAt: now, updatedAt: now, deletedAt: null });
    tx.objectStore('notes').put(mk('big', 'ძალიან დიდი', 'ა'.repeat(400000)));
    tx.objectStore('notes').put(mk('small', 'პატარა', 'ok'));
    tx.oncomplete = () => { d.close(); resolve(); }; tx.onerror = () => reject(tx.error); };
}));
await page.goto('http://127.0.0.1:4190/'); await page.waitForSelector('ul li');
await page.click('nav a:has-text("პარამეტრები")');
const acc = page.locator('section[aria-labelledby="account-heading"]');
await acc.locator('button:has-text("ან ელფოსტით")').click();
await acc.locator('input[name=email]').fill('me@example.com');
await acc.locator('input[name=password]').fill('correct-horse-9');
await acc.getByRole('button', { name: 'ანგარიშის შექმნა', exact: true }).click();
await acc.locator('text=ვერ მოხერხდა').waitFor({ timeout: 10000 });
const panel = (await acc.innerText()).replace(/\n+/g, ' | ');
console.log('   account card:', panel);
ok('the message names the true reason (too large), not a generic one', panel.includes('ძალიან დიდია'));
ok('it says the changes are safe on the phone', panel.includes('უსაფრთხოდ'));
ok('the other note still got through', (await dump('notes')).map((n) => n.id).join() === 'small');
await page.screenshot({ path: `${OUT}/big-1.png`, clip: { x: 0, y: 0, width: 360, height: 420 } });
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
